describe('PDF extraction', () => {
  it('extracts text with explicit page markers', async () => {
    const pdf = buildPdf(['Residual connections ease optimisation.', 'Second page text.']);
    const result = await extractArtifact('paper.pdf', pdf);
    expect(result.text).toContain('[page 1]');
    expect(result.text).toContain('Residual connections ease optimisation.');
    expect(result.text).toContain('[page 2]');
    expect(result.text).toContain('Second page text.');
    expect(result.mediaType).toBe('application/pdf');
  }, 60_000);

  it('reports an image-only PDF as having no extractable text', async () => {
    // A valid PDF whose single page draws nothing.
    const blank = buildPdf(['']);
    await expect(extractArtifact('scan.pdf', blank)).rejects.toThrow(/scanned PDF/);
  }, 60_000);

  it('refuses a malformed PDF', async () => {
    await expect(extractArtifact('broken.pdf', utf8('%PDF-1.4\nnot really\n'))).rejects.toThrow(
      ExtractionError,
    );
  }, 60_000);

  it('stops at the page limit and says so', async () => {
    const many = buildPdf(
      Array.from({ length: MAX_PDF_PAGES + 3 }, (_, index) => `Page ${String(index + 1)} text.`),
    );
    const result = await extractArtifact('long.pdf', many);
    expect(result.warnings.join(' ')).toContain(`only the first ${String(MAX_PDF_PAGES)}`);
    expect(result.text).toContain(`[page ${String(MAX_PDF_PAGES)}]`);
    expect(result.text).not.toContain(`[page ${String(MAX_PDF_PAGES + 1)}]`);
  }, 120_000);

  it('stops when extraction takes too long', async () => {
    // The budget is checked by the page loop itself. A timer alone would never
    // fire: page extraction is CPU-bound and resolves through microtasks.
    const many = buildPdf(Array.from({ length: 60 }, (_, index) => `Page ${String(index)}.`));
    await expect(extractArtifact('slow.pdf', many, { timeoutMs: -1 })).rejects.toThrow(
      /taking too long/,
    );
    expect(EXTRACTION_TIMEOUT_MS).toBe(60_000);
  }, 60_000);
});

