/**
 * Local artifact ingestion (v2 runbook P01–P04).
 *
 * Fixtures are built here rather than committed, so the repository never
 * carries a binary blob, and **no fixture is ever executed**: a `.py` file is
 * decoded and stored as text, exactly as a researcher's own file would be.
 *
 * The notebook fixture deliberately contains a base64 image output and a
 * credential-shaped string in an output cell. Neither may appear in the
 * extracted text, because notebook outputs are where secrets leak in practice.
 */
import { describe, expect, it } from 'vitest';
import {
  ALLOWED_EXTENSIONS,
  EXTRACTION_TIMEOUT_MS,
  ExtractionError,
  MAX_EXTRACTED_CHARACTERS,
  MAX_PDF_PAGES,
  MAX_UPLOAD_BYTES,
  extensionOf,
  extractArtifact,
  isAllowedExtension,
  mediaTypeFor,
} from '../src/artifacts/index.js';
import {
  PersonalNotFoundError,
  PersonalValidationError,
  archiveArtifact,
  countArtifacts,
  createArtifact,
  createProject,
  getArtifactInProject,
  listArtifacts,
  openPersonalDatabase,
  restoreArtifact,
  selectArtifactsForContext,
} from '../src/personal/index.js';

const utf8 = (text: string): Uint8Array => new TextEncoder().encode(text);

