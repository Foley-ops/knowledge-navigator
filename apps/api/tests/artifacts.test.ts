/* P02 — text and code                                                         */
/* -------------------------------------------------------------------------- */

describe('text and code extraction', () => {
  it('accepts every allowed text extension', async () => {
    for (const extension of ALLOWED_EXTENSIONS) {
      if (extension === '.pdf' || extension === '.ipynb') continue;
      const result = await extractArtifact(`paper${extension}`, utf8('hello, research\n'));
      expect(result.text, extension).toBe('hello, research\n');
      expect(result.extension).toBe(extension);
      expect(result.characterCount).toBe(result.text.length);
      expect(result.sha256).toMatch(/^[0-9a-f]{64}$/);
    }
  });

  it('stores code as text and does not execute it', async () => {
    const source = [
      'import os',
      'os.system("touch /tmp/navigator-should-never-exist")',
      'print("hello")',
    ].join('\n');
    const result = await extractArtifact('run.py', utf8(source));
    expect(result.text).toContain('os.system');
    expect(result.mediaType).toBe('text/plain');
    const { existsSync } = await import('node:fs');
    expect(existsSync('/tmp/navigator-should-never-exist')).toBe(false);
  });

  it('normalises newlines and strips a byte-order mark', async () => {
    const result = await extractArtifact('notes.md', utf8('﻿one\r\ntwo\rthree\n'));
    expect(result.text).toBe('one\ntwo\nthree\n');
  });

  it('refuses an unsupported extension, naming what it does read', async () => {
    await expect(extractArtifact('slides.pptx', utf8('x'))).rejects.toThrow(ExtractionError);
    await expect(extractArtifact('slides.pptx', utf8('x'))).rejects.toThrow(/not read/);
    await expect(extractArtifact('noextension', utf8('x'))).rejects.toThrow(/no extension/);
  });

  it('refuses an empty file and one over the size limit', async () => {
    await expect(extractArtifact('empty.txt', new Uint8Array(0))).rejects.toThrow(/empty/);
    const huge = new Uint8Array(MAX_UPLOAD_BYTES + 1).fill(0x61);
    await expect(extractArtifact('huge.txt', huge)).rejects.toThrow(/the limit is/);
  });

  it('refuses binary content wearing a text extension', async () => {
    const png = new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 13]);
    await expect(extractArtifact('image.txt', png)).rejects.toThrow(/binary data/);

    const mostlyControls = new Uint8Array(200).fill(0x01);
    await expect(extractArtifact('control.txt', mostlyControls)).rejects.toThrow(/binary data/);
  });

  it('warns rather than fails on invalid UTF-8', async () => {
    const bytes = new Uint8Array([...utf8('good '), 0xff, 0xfe, ...utf8(' text')]);
    const result = await extractArtifact('mixed.txt', bytes);
    expect(result.text).toContain('good');
    expect(result.warnings.join(' ')).toContain('not valid UTF-8');
  });

  it('caps extraction and says so', async () => {
    const long = 'a'.repeat(MAX_EXTRACTED_CHARACTERS + 5_000);
    const result = await extractArtifact('long.txt', utf8(long));
    expect(result.characterCount).toBe(MAX_EXTRACTED_CHARACTERS);
    expect(result.warnings.join(' ')).toContain('Extraction stopped at');
  });

  it('refuses a file that is only whitespace', async () => {
    await expect(extractArtifact('blank.txt', utf8('   \n\n  \n'))).rejects.toThrow(
      /No text could be extracted/,
    );
  });

  it('knows its own vocabulary', () => {
    expect(extensionOf('/a/b/paper.PDF')).toBe('.pdf');
    expect(extensionOf('noextension')).toBe('');
    expect(extensionOf('.hidden')).toBe('');
    expect(isAllowedExtension('.rs')).toBe(true);
    expect(isAllowedExtension('.exe')).toBe(false);
    expect(mediaTypeFor('.ipynb')).toBe('application/x-ipynb+json');
  });
});

