describe('artifact storage', () => {
  const sample = {
    label: 'ResNet paper',
    originalName: 'resnet.pdf',
    mediaType: 'application/pdf',
    byteCount: 1234,
    characterCount: 42,
    sha256: 'a'.repeat(64),
    warnings: ['One page could not be read.'],
    extractedText: '[page 1]\nResidual connections ease optimisation.',
  };

  it('creates, reads back text deliberately, and lists metadata only', () => {
    const db = openPersonalDatabase(':memory:');
    try {
      const project = createProject(db, { title: 'Papers' });
      const created = createArtifact(db, project.id, sample);
      expect(created.deduplicated).toBe(false);
      expect(created.artifact.label).toBe('ResNet paper');
      expect(created.artifact.warnings).toEqual(['One page could not be read.']);

      // A listing carries no extracted text at all.
      const listed = listArtifacts(db, project.id);
      expect(listed).toHaveLength(1);
      expect(Object.keys(listed[0]!)).not.toContain('extractedText');

      const full = getArtifactInProject(db, project.id, created.artifact.id);
      expect(full.extractedText).toContain('Residual connections');
    } finally {
      db.close();
    }
  });

  it('never stores the original bytes', () => {
    const db = openPersonalDatabase(':memory:');
    try {
      const columns = (db.prepare('PRAGMA table_info(artifacts)').all() as { name: string }[]).map(
        (column) => column.name,
      );
      expect(columns).toContain('extracted_text');
      expect(columns).toContain('sha256');
      for (const forbidden of ['bytes', 'blob', 'content', 'data', 'original']) {
        expect(columns.some((name) => name === forbidden)).toBe(false);
      }
      // `original_name` is the file's name, not its contents.
      expect(columns).toContain('original_name');
    } finally {
      db.close();
    }
  });

  it('deduplicates the same bytes inside one project, but not across projects', () => {
    const db = openPersonalDatabase(':memory:');
    try {
      const one = createProject(db, { title: 'One' });
      const two = createProject(db, { title: 'Two' });

      expect(createArtifact(db, one.id, sample).deduplicated).toBe(false);
      const again = createArtifact(db, one.id, { ...sample, label: 'Renamed' });
      expect(again.deduplicated).toBe(true);
      expect(again.artifact.label).toBe('ResNet paper');
      expect(countArtifacts(db, one.id)).toBe(1);

      expect(createArtifact(db, two.id, sample).deduplicated).toBe(false);
      expect(countArtifacts(db)).toBe(2);
    } finally {
      db.close();
    }
  });

  it('archives, restores, and un-archives on a repeat upload', () => {
    const db = openPersonalDatabase(':memory:');
    try {
      const project = createProject(db, { title: 'Lifecycle' });
      const artifact = createArtifact(db, project.id, sample).artifact;

      archiveArtifact(db, project.id, artifact.id);
      expect(listArtifacts(db, project.id)).toHaveLength(0);
      expect(listArtifacts(db, project.id, { includeArchived: true })).toHaveLength(1);

      restoreArtifact(db, project.id, artifact.id);
      expect(listArtifacts(db, project.id)).toHaveLength(1);

      archiveArtifact(db, project.id, artifact.id);
      const repeat = createArtifact(db, project.id, sample);
      expect(repeat.deduplicated).toBe(true);
      expect(repeat.artifact.archivedAt).toBeNull();
    } finally {
      db.close();
    }
  });

  it('refuses an artifact from another project, and an unknown project', () => {
    const db = openPersonalDatabase(':memory:');
    try {
      const one = createProject(db, { title: 'One' });
      const two = createProject(db, { title: 'Two' });
      const artifact = createArtifact(db, one.id, sample).artifact;

      expect(() => getArtifactInProject(db, two.id, artifact.id)).toThrow(PersonalNotFoundError);
      expect(() => archiveArtifact(db, two.id, artifact.id)).toThrow(PersonalNotFoundError);
      expect(() => createArtifact(db, 'nope', sample)).toThrow(PersonalNotFoundError);
    } finally {
      db.close();
    }
  });

  it('rejects malformed metadata', () => {
    const db = openPersonalDatabase(':memory:');
    try {
      const project = createProject(db, { title: 'Validation' });
      expect(() => createArtifact(db, project.id, { ...sample, sha256: 'nope' })).toThrow(
        PersonalValidationError,
      );
      expect(() => createArtifact(db, project.id, { ...sample, extractedText: '' })).toThrow(
        PersonalValidationError,
      );
      expect(() => createArtifact(db, project.id, { ...sample, extra: 1 })).toThrow(
        PersonalValidationError,
      );
    } finally {
      db.close();
    }
  });

  it('selects only the artifacts a caller named, from its own project', () => {
    const db = openPersonalDatabase(':memory:');
    try {
      const one = createProject(db, { title: 'One' });
      const two = createProject(db, { title: 'Two' });
      const mine = createArtifact(db, one.id, sample).artifact;
      const theirs = createArtifact(db, two.id, { ...sample, sha256: 'b'.repeat(64) }).artifact;
      const archived = createArtifact(db, one.id, {
        ...sample,
        sha256: 'c'.repeat(64),
        label: 'Archived',
      }).artifact;
      archiveArtifact(db, one.id, archived.id);

      const selected = selectArtifactsForContext(db, one.id, [
        mine.id,
        theirs.id,
        archived.id,
        'not-an-id',
      ]);
      expect(selected.map((artifact) => artifact.id)).toEqual([mine.id]);
    } finally {
      db.close();
    }
  });
});
