const NOTEBOOK = JSON.stringify({
  cells: [
    { cell_type: 'markdown', source: ['# Recall experiment\n', '\n', 'Measuring at 512px.'] },
    { cell_type: 'code', source: 'import torch\nprint(model)\n', execution_count: 3 },
    {
      cell_type: 'code',
      source: 'display(figure)\n',
      outputs: [
        {
          output_type: 'display_data',
          data: {
            'image/png':
              'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==',
          },
        },
        { output_type: 'stream', text: 'SENTINEL-NOTEBOOK-OUTPUT-SECRET-91af\n' },
      ],
    },
    { cell_type: 'raw', source: 'raw cell contents' },
  ],
  metadata: { language_info: { name: 'python', version: '3.12' }, widgets: { state: {} } },
  nbformat: 4,
});

describe('notebook extraction', () => {
  it('keeps markdown and code source in cell order', async () => {
    const result = await extractArtifact('experiment.ipynb', utf8(NOTEBOOK));
    expect(result.text).toContain('# Recall experiment');
    expect(result.text).toContain('import torch');
    expect(result.text).toContain('cell 1 · markdown');
    expect(result.text).toContain('cell 2 · code');
    expect(result.text).toContain('language python');
    expect(result.mediaType).toBe('application/x-ipynb+json');
  });

  it('discards every output, including base64 images and a leaked secret', async () => {
    const result = await extractArtifact('experiment.ipynb', utf8(NOTEBOOK));
    expect(result.text).not.toContain('iVBORw0KGgo');
    expect(result.text).not.toContain('SENTINEL-NOTEBOOK-OUTPUT-SECRET-91af');
    expect(result.text).not.toContain('image/png');
    expect(result.text).not.toContain('execution_count');
    expect(result.text).not.toContain('widgets');
    expect(result.warnings.join(' ')).toContain('outputs, attachments and execution counts');
  });

  it('skips a cell that is neither markdown nor code, and says how many', async () => {
    const result = await extractArtifact('experiment.ipynb', utf8(NOTEBOOK));
    expect(result.warnings.join(' ')).toContain('1 cell(s) were neither markdown nor code');
    expect(result.text).not.toContain('raw cell contents');
  });

  it('refuses malformed JSON and a notebook with no cells', async () => {
    await expect(extractArtifact('broken.ipynb', utf8('{not json'))).rejects.toThrow(
      /not valid JSON/,
    );
    await expect(extractArtifact('empty.ipynb', utf8('{"metadata":{}}'))).rejects.toThrow(
      /no cell list/,
    );
    await expect(
      extractArtifact('silent.ipynb', utf8('{"cells":[{"cell_type":"code","source":""}]}')),
    ).rejects.toThrow(/no markdown or code text/);
  });
});

